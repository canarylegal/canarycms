@pytest.mark.parametrize("rollback", [False, True])
def test_parallel_creation_and_retry_are_one_operation(
    db, tmp_path, monkeypatch, rollback
):
    if db.bind.dialect.name != "postgresql":
        pytest.skip("isolated PostgreSQL required")
    user = add_user(db)
    case = add_case(db, fee_earner_user_id=user.id)
    db.commit()
    uid, cid, key = user.id, case.id, str(uuid.uuid4())
    db.rollback()
    locked, attempted = Event(), Event()
    from app.file_storage import FILES_ROOT

    root = FILES_ROOT

    def render(*a, **kw):
        locked.set()
        assert attempted.wait(15)
        if rollback:
            raise OSError("Injected generation failure")
        return b"generated bytes", "application/test"

    monkeypatch.setattr(creation, "merge_compose_docx_bytes", render)
    payload = ComposeOfficeDocumentIn(original_filename="Concurrent.docx")

    def run():
        with SessionLocal() as session:
            session.info["document_operation_key"] = key
            return creation.compose_office_document(
                cid, payload, session.get(User, uid), session
            )

    def contender():
        assert locked.wait(15)
        try:
            with pytest.raises(HTTPException) as error:
                run()
            assert error.value.status_code == 429
        finally:
            attempted.set()

    with ThreadPoolExecutor(max_workers=2) as pool:
        first, second = pool.submit(run), pool.submit(contender)
        if rollback:
            with pytest.raises(OSError):
                first.result(20)
        else:
            first.result(20)
        second.result(20)
    monkeypatch.setattr(
        creation,
        "merge_compose_docx_bytes",
        lambda *a, **kw: (b"generated bytes", "application/test"),
    )
    response = run()
    assert run() == response
    with SessionLocal() as session:
        assert (
            session.scalar(
                select(func.count()).select_from(File).where(File.case_id == cid)
            )
            == 1
        )
        row = session.get(File, uuid.UUID(response["id"]))
        assert (root / row.storage_path).read_bytes() == b"generated bytes"
        assert row.checksum


def test_parallel_signing_completion_publishes_one_artifact_pair(db, monkeypatch):
    if db.bind.dialect.name != "postgresql":
        pytest.skip("isolated PostgreSQL required")
    from app import canary_sign_service as signing
    from app.models import CanarySignRequest, CanarySignStatus

    user = add_user(db)
    case = add_case(db, fee_earner_user_id=user.id)
    source = signing._save_case_file(
        db,
        case_id=case.id,
        owner_id=user.id,
        folder_path="",
        filename="Source.pdf",
        mime_type="application/pdf",
        raw=b"source pdf",
    )
    req = CanarySignRequest(
        id=uuid.uuid4(),
        case_id=case.id,
        source_file_id=source.id,
        snapshot_pdf_file_id=source.id,
        sent_by_user_id=user.id,
        subject="Synthetic concurrency signing",
        expires_at=datetime(
            2099, 1, 1, tzinfo=timezone.utc
        ),
        status=CanarySignStatus.pending,
    )
    db.add(req)
    db.commit()
    rid, cid = req.id, case.id
    db.rollback()
    rendering, attempted = Event(), Event()
    calls = []

    def stamp(*a):
        calls.append("render")
        rendering.set()
        assert attempted.wait(15)
        return b"signed pdf"

    monkeypatch.setattr(signing, "stamp_signed_pdf", stamp)
    monkeypatch.setattr(
        signing, "build_audit_certificate_pdf", lambda **kw: b"certificate pdf"
    )
    monkeypatch.setattr(signing, "_notify_staff_completed", lambda *a: None)
    monkeypatch.setattr(signing, "log_portal_activity", lambda *a, **kw: None)

    def run(second=False):
        if second:
            assert rendering.wait(15)
            attempted.set()
        with SessionLocal() as session:
            signing.complete_signing_request(
                session, session.get(CanarySignRequest, rid)
            )

    with ThreadPoolExecutor(max_workers=2) as pool:
        a, b = pool.submit(run), pool.submit(run, True)
        a.result(20)
        b.result(20)
    with SessionLocal() as session:
        assert session.get(CanarySignRequest, rid).status == CanarySignStatus.completed
        assert (
            session.scalar(
                select(func.count()).select_from(File).where(File.case_id == cid)
            )
            == 3
        )
    assert calls == ["render"]
